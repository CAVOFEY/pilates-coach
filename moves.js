const io = (x) => (x < 0.5 ? 4 * x * x * x : 1 - Math.pow(-2 * x + 2, 3) / 2);
/** 示范动画：第 t 秒时的关节位置（在几个关键姿势之间来回过渡） */
export function moveJoints(m, t, still = false) {
  const n = m.keys.length;
  if (still) return m.keys[Math.min(1, n - 1)];
  const seg = m.beat + m.hold, u = (t % (seg * n)) / seg, i = Math.floor(u), k = io(Math.min(1, ((u - i) * seg) / m.beat));
  const A = m.keys[i % n], B = m.keys[(i + 1) % n], J = {};
  for (const key in A) J[key] = [A[key][0] + (B[key][0] - A[key][0]) * k, A[key][1] + (B[key][1] - A[key][1]) * k, A[key][2] + (B[key][2] - A[key][2]) * k];
  return J;
}
